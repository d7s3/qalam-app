    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $textName = 'متن الرواد';

        if (HadithText::where('name', $textName)->exists()) {
            $this->warn("المتن \"{$textName}\" موجود بالفعل، لن يتم إنشاء أي بيانات جديدة.");

            return self::FAILURE;
        }

        $text = HadithText::create(['name' => $textName]);

        foreach (self::HADITHS as $matn) {
            $hadith = Hadith::create([
                'hadith_text_id' => $text->id,
                'name' => Str::limit($matn, 50),
            ]);

            HadithLine::create([
                'hadith_id' => $hadith->id,
                'line_number' => 1,
                'text' => $matn,
            ]);
        }

        $this->info('تم إنشاء المتن "'.$textName.'" وإضافة '.count(self::HADITHS).' حديثًا بنجاح.');

        return self::SUCCESS;
    }
